"""Writes oxeegen/managed/config.yaml, the Oxee Hermes managed scope, from the single source
plugins/model-providers/oxeegen/oxeegen.json.

The managed scope (hermes_cli/managed_scope.py) overlays the user's config and its keys cannot be
changed from the app. The desktop points the backend at it with HERMES_MANAGED_DIR.

    python3 oxeegen/scripts/gen-managed.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "plugins/model-providers/oxeegen/oxeegen.json"
TARGET = ROOT / "oxeegen/managed/config.yaml"


def render(cfg: dict) -> str:
    key = "${" + cfg["api_key_env"] + "}"
    url = "${" + cfg["base_url_env"] + "}"
    voice = cfg["voice"]
    provider = cfg["provider"]
    return f"""# GENERATED by oxeegen/scripts/gen-managed.py from {SOURCE.relative_to(ROOT)} — do not edit.
#
# Oxee Hermes managed scope: values the app cannot change. {cfg["api_key_env"]} / {cfg["base_url_env"]}
# are the ACTIVE pair, derived from the region the user stored ({cfg["region_env"]}) and that region's
# own key by the provider plugin and the desktop. References left unresolved stay verbatim, so a
# missing key or region fails instead of reaching another endpoint.

model:
  provider: {provider}
  default: {cfg["models"]["main"]}

# No second source of inference: no fallbacks, no custom endpoints, no other provider.
fallback_providers: []
custom_providers: []
model_catalog:
  enabled: false
  allowed_providers: [{provider}]

# Voice goes to Oxeegen's OpenAI-compatible audio API with the same key and region.
stt:
  provider: openai
  openai:
    api_key: "{key}"
    base_url: "{url}"
    model: {voice["stt_model"]}
tts:
  provider: openai
  openai:
    api_key: "{key}"
    base_url: "{url}"
    model: {voice["tts_model"]}
    voice: {voice["tts_voice"]}

# Nothing is reported to Nous.
telemetry:
  shared_metrics:
    enabled: false
    send: false
"""


if __name__ == "__main__":
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(json.loads(SOURCE.read_text(encoding="utf-8"))), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
