"""Writes the Oxee Hermes managed scope, oxeegen/managed/config.yaml (pinned) and defaults.yaml
(what a profile starts with), from the single source plugins/model-providers/oxeegen/oxeegen.json.

The managed scope (hermes_cli/managed_scope.py) overlays the user's config and its keys cannot be
changed from the app. defaults.yaml (managed_scope.load_managed_defaults) pins nothing: it sits
under the user's config, so the Oxeegen model is where a profile starts and the user may pick any
other provider, custom endpoint or fallback.
The desktop points the backend at it with HERMES_MANAGED_DIR.

    python3 oxeegen/scripts/gen-managed.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "plugins/model-providers/oxeegen/oxeegen.json"
TARGET = ROOT / "oxeegen/managed/config.yaml"
DEFAULTS = ROOT / "oxeegen/managed/defaults.yaml"


def render(cfg: dict) -> str:
    key = "${" + cfg["api_key_env"] + "}"
    url = "${" + cfg["base_url_env"] + "}"
    voice = cfg["voice"]
    return f"""# GENERATED by oxeegen/scripts/gen-managed.py from {SOURCE.relative_to(ROOT)} — do not edit.
#
# Oxee Hermes managed scope: values the app cannot change (the model is not one: Oxeegen is the
# default, the user picks freely). {cfg["api_key_env"]} / {cfg["base_url_env"]}
# are the ACTIVE pair, derived from the region the user stored ({cfg["region_env"]}) and that region's
# own key by the provider plugin and the desktop. References left unresolved stay verbatim, so a
# missing key or region fails instead of reaching another endpoint.

# Voice is chained: Oxeegen STT -> Hermes turn -> Oxeegen TTS, on Oxeegen's OpenAI-compatible
# audio API with the same key and region. Settings > Voice hides these choices (settings-policy.ts).
# The TTS voice is the user's pick (default tts.openai.voice in hermes_cli/config_defaults.py).
voice:
  voice_chat_mode: chained
stt:
  enabled: true
  streaming: false
  provider: openai
  openai:
    api_key: "{key}"
    base_url: "{url}"
    model: {voice["stt_model"]}
tts:
  provider: openai
  openai:
    api_key: "{key}"
    base_url: "{url}"
    model: {voice["tts_model"]}

# Nothing is reported to Nous.
telemetry:
  shared_metrics:
    enabled: false
    send: false

# No Nous identity: no guest minted at Nous Research, so no Nous free trial and no "Sign in" to it.
nous:
  guest: false
"""


def render_defaults(cfg: dict) -> str:
    return f"""# GENERATED by oxeegen/scripts/gen-managed.py from {SOURCE.relative_to(ROOT)} — do not edit.
#
# Oxee Hermes managed defaults: what a profile starts with, NOT pinned. The user's config.yaml wins,
# so Settings > Model, the model picker and Settings > Providers can move to any other provider.

model:
  provider: {cfg["provider"]}
  default: {cfg["models"]["main"]}
"""


if __name__ == "__main__":
    cfg = json.loads(SOURCE.read_text(encoding="utf-8"))
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(cfg), encoding="utf-8")
    DEFAULTS.write_text(render_defaults(cfg), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} and {DEFAULTS.relative_to(ROOT)}")
